import { readFileSync, writeFileSync } from "node:fs";
import { themeTokens } from "../src/tokens.js";

const header = "/* Generated by themes generate:theme. Edit src/tokens.ts. */\n";
function declarations(theme: "light" | "dark", indentation = "  "): string {
  return `${indentation}color-scheme: ${theme};\n${Object.entries(themeTokens[theme])
    .map(([key, value]) => `${indentation}--${key}: ${value};`)
    .join("\n")}`;
}
const styles = `${header}:root {\n${declarations("light")}\n}\n\n.dark,\n[data-theme="dark"] {\n${declarations("dark")}\n}\n\n@media (prefers-color-scheme: dark) {\n  :root:not(.light):not(.dark):not([data-theme="light"]):not([data-theme="dark"]) {\n${declarations("dark", "    ")}\n  }\n}\n`;
const colors = Object.keys(themeTokens.light).filter(
  (name) => name !== "radius" && !name.startsWith("shadow-"),
);
const mappings = [
  ...colors.map((name) => `  --color-${name}: var(--${name});`),
  "  --radius-sm: calc(var(--radius) - 4px);",
  "  --radius-md: calc(var(--radius) - 2px);",
  "  --radius-lg: var(--radius);",
  "  --radius-xl: calc(var(--radius) + 4px);",
  "  --shadow-soft: var(--shadow-soft-value);",
  "  --shadow-popover: var(--shadow-popover-value);",
];
const tailwind = `${header}@import "./styles.css";\n\n@custom-variant dark (&:where(.dark, .dark *));\n\n@theme inline {\n${mappings.join("\n")}\n}\n`;
for (const [name, content] of Object.entries({ "styles.css": styles, "tailwind.css": tailwind })) {
  const target = new URL(`../${name}`, import.meta.url);
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== content)
      throw new Error(`Outdated theme artifact: ${name}. Run generate:theme.`);
  } else writeFileSync(target, content);
}
